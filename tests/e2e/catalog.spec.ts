import { test, expect } from '@playwright/test'

test('catalog → comparison → estimate → inquiry', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Смотреть каталог' }).click()
  await expect(page.locator('.product-card')).toHaveCount(12)
  await page.getByRole('searchbox').fill('Линия')
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Подробнее: Кухня «Линия»' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Закрыть', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Открыть сравнение', exact: true }).click()
  await page.getByRole('button', { name: 'Выбрать материал' }).first().click()
  await expect(page.locator('.estimate-total')).toContainText('269')
  await page.getByLabel('Ширина', { exact: true }).fill('200')
  await expect(page.locator('.estimate-total')).toHaveCount(0)
  await page.getByRole('button', { name: 'Обновить расчёт' }).click()
  await expect(page.locator('.estimate-total')).toContainText('299')
  await page.getByRole('checkbox', { name: /Проектирование/ }).check()
  await expect(page.locator('.estimate-total')).toContainText('311')
  await page.getByRole('button', { name: 'Передать параметры мастеру' }).click()
  await page.getByLabel('Имя', { exact: true }).fill('Демонстрационный тест')
  await page.getByLabel('Телефон', { exact: true }).fill('+70000000000')
  await page.getByRole('button', { name: 'Сохранить обращение' }).click()
  await expect(page.getByRole('status')).toContainText('сохранено в демонстрационной базе')
})

test('API paths return JSON and SPA paths return the application', async ({ request }) => {
  const response = await request.get('/api/v1/missing')
  expect(response.status()).toBe(404)
  expect(response.headers()['content-type']).toContain('application/problem+json')
  expect((await request.get('/health/ready')).status()).toBe(200)
  expect((await request.get('/catalog')).headers()['content-type']).toContain('text/html')
})
